#include <iostream>
using namespace std;

int main() {
    int a = 4, b = 8;
    cout << (a & b) << endl;
    cout << (a | b) << endl;
    cout << (a ^ b) << endl;
    cout << (a << 2) << endl;
    cout << (b >> 1) << endl;
    
    return 0;
}                                                                                               